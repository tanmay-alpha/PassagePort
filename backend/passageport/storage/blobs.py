"""Storage for the original uploaded bytes.

Blob keys are always generated by the server (32 hex characters) and never derived from anything
a client sent, so a key can be used as a file name without any path-traversal risk. Both stores
refuse keys of any other shape as a second line of defence.
"""

from __future__ import annotations

import contextlib
import logging
import os
import re
import secrets
import time
from collections.abc import Sequence
from pathlib import Path
from typing import Protocol

from sqlalchemy import Connection, Engine, delete, insert, select

from passageport.config import Settings
from passageport.db.repos import all_blob_keys
from passageport.db.schema import blobs, documents

log = logging.getLogger("passageport.storage")

_KEY = re.compile(r"^[0-9a-f]{32}$")
_TMP_SUFFIX = ".tmp"


class BlobNotFoundError(KeyError):
    """The requested blob does not exist (deleted, or the storage volume was replaced)."""


def new_blob_key() -> str:
    return secrets.token_hex(16)


def _check(key: str) -> str:
    if not _KEY.fullmatch(key):
        raise ValueError("invalid blob key")
    return key


class BlobStore(Protocol):
    """Where uploaded bytes live.

    A blob belongs to exactly one document row. The two ``remove_*`` methods exist because the
    two backends reach "blob and row disappear together" differently: the database store deletes
    inside the caller's transaction, the filesystem store can only unlink once that transaction
    has committed. Callers always invoke both, each at its point, and the store that does not
    need the call ignores it.
    """

    def put(self, key: str, data: bytes, conn: Connection | None = None) -> None:
        """Store a blob. ``conn`` is the open transaction that inserts the owning document."""
        ...

    def get(self, key: str) -> bytes: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None:
        """Remove one blob on its own (maintenance and tests)."""
        ...

    def remove_in_transaction(self, conn: Connection, keys: Sequence[str]) -> None:
        """Call inside the transaction that deletes the owning rows."""
        ...

    def remove_files(self, keys: Sequence[str]) -> None:
        """Call after that transaction committed - or after an insert was rolled back."""
        ...


class FsBlobStore:
    """Files under ``root``, fanned out by the first two key characters."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        _check(key)
        return self.root / key[:2] / key

    def put(self, key: str, data: bytes, conn: Connection | None = None) -> None:
        """Write to a temp file and rename, so a crash never leaves a truncated blob behind.

        A file cannot join a database transaction: if the caller's transaction then fails, it
        removes the file again (``remove_files``), and the orphan sweep covers a crash in between.
        """
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(f"{key}.{secrets.token_hex(4)}{_TMP_SUFFIX}")
        try:
            with tmp.open("wb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(tmp, path)
        finally:
            with contextlib.suppress(FileNotFoundError):
                tmp.unlink()

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError:
            raise BlobNotFoundError(key) from None

    def delete(self, key: str) -> None:
        with contextlib.suppress(FileNotFoundError):
            self._path(key).unlink()

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def remove_in_transaction(self, conn: Connection, keys: Sequence[str]) -> None:
        """Nothing yet: unlinking before the commit could lose a file whose row survives."""

    def remove_files(self, keys: Sequence[str]) -> None:
        for key in keys:
            try:
                self.delete(key)
            except OSError as exc:
                # The row is already gone; the orphan sweep removes what could not be deleted now.
                log.warning("could not delete a stored file: %s", type(exc).__name__)

    def sweep(self, live_keys: set[str], min_age_seconds: float) -> int:
        """Delete blobs no document refers to, and leftover temp files. Returns the number removed.

        Only files older than ``min_age_seconds`` are touched: an upload writes its blob before
        its database row is committed, and that window must not look like an orphan.
        """
        cutoff = time.time() - min_age_seconds
        removed = 0
        for path in self.root.glob("*/*"):
            if not path.is_file():
                continue
            is_orphan = path.name.endswith(_TMP_SUFFIX) or path.name not in live_keys
            try:
                if is_orphan and path.stat().st_mtime <= cutoff:
                    path.unlink()
                    removed += 1
            except OSError:
                continue
        return removed


class DbBlobStore:
    """Blobs in the ``blobs`` table, for hosts that only offer a database.

    Blob rows are written and deleted in the same transaction as their document row, so the two
    can never disagree - there is no window in which uploaded bytes exist without a document that
    a user could delete.
    """

    def __init__(self, engine: Engine) -> None:
        self.engine = engine

    @staticmethod
    def _put(conn: Connection, key: str, data: bytes) -> None:
        conn.execute(delete(blobs).where(blobs.c.key == key))
        conn.execute(insert(blobs).values(key=key, data=data))

    def put(self, key: str, data: bytes, conn: Connection | None = None) -> None:
        _check(key)
        if conn is not None:
            self._put(conn, key, data)
            return
        with self.engine.begin() as own:
            self._put(own, key, data)

    def get(self, key: str) -> bytes:
        _check(key)
        with self.engine.connect() as conn:
            data = conn.execute(select(blobs.c.data).where(blobs.c.key == key)).scalar()
        if data is None:
            raise BlobNotFoundError(key)
        return bytes(data)

    def delete(self, key: str) -> None:
        _check(key)
        with self.engine.begin() as conn:
            conn.execute(delete(blobs).where(blobs.c.key == key))

    def exists(self, key: str) -> bool:
        _check(key)
        with self.engine.connect() as conn:
            return conn.execute(select(blobs.c.key).where(blobs.c.key == key)).first() is not None

    def remove_in_transaction(self, conn: Connection, keys: Sequence[str]) -> None:
        for key in keys:
            _check(key)
        if keys:
            conn.execute(delete(blobs).where(blobs.c.key.in_(list(keys))))

    def remove_files(self, keys: Sequence[str]) -> None:
        """Nothing to do: the rows went with the transaction."""

    def sweep(self) -> int:
        """Delete blob rows no document refers to. Returns the number removed.

        Needs no age threshold: a blob is committed together with its document, so a statement
        can never see one without the other while an upload is in flight.
        """
        with self.engine.begin() as conn:
            result = conn.execute(delete(blobs).where(blobs.c.key.not_in(select(documents.c.blob_key))))
        return result.rowcount


def get_blob_store(settings: Settings, engine: Engine) -> FsBlobStore | DbBlobStore:
    if settings.blob_backend == "db":
        return DbBlobStore(engine)
    return FsBlobStore(settings.data_dir / "blobs")


def sweep_orphan_blobs(engine: Engine, settings: Settings, min_age_seconds: float = 3600.0) -> int:
    """Remove stored bytes that no document row refers to (left behind by a crash between writing
    a blob and committing its document, or between deleting a document and its blob)."""
    store = get_blob_store(settings, engine)
    if isinstance(store, DbBlobStore):
        return store.sweep()
    with engine.connect() as conn:
        live = all_blob_keys(conn)
    return store.sweep(live, min_age_seconds)
